import java.util.List;
import java.util.Objects;
import solutions.dirx.identity.connector.sdk.api.model.Attribute;
import solutions.dirx.identity.connector.sdk.api.model.Identifier;

/**
 * Result of {@link CreateOp#create}.
 *
 * @param identifier the identifier of the created object, as assigned by the target
 * @param attributes attributes generated by the target (e.g. an id or creation timestamp);
 *                   {@code null} is normalized to an empty list
 */
public record CreateResult(Identifier identifier, List<Attribute> attributes) {

    /** Validates and copies the components. */
    public CreateResult {
        Objects.requireNonNull(identifier, "identifier");
        attributes = attributes == null ? List.of() : List.copyOf(attributes);
    }

    /**
     * Creates a result without generated attributes.
     *
     * @param identifier the identifier of the created object
     * @return the result
     */
    public static CreateResult of(Identifier identifier) {
        return new CreateResult(identifier, List.of());
    }
}
