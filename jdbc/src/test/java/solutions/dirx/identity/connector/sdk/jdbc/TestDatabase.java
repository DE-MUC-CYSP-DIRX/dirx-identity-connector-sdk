package solutions.dirx.identity.connector.sdk.jdbc;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.UUID;
import solutions.dirx.identity.connector.sdk.api.config.ConnectionSettings;
import solutions.dirx.identity.connector.sdk.api.config.MapConnectorConfiguration;
import solutions.dirx.identity.connector.sdk.api.model.SecretValue;

/** Creates in-memory HSQLDB databases for tests. */
final class TestDatabase {

    private TestDatabase() {
    }

    static String create() {
        String url = "jdbc:hsqldb:mem:" + UUID.randomUUID() + ";shutdown=false";
        try (Connection c = DriverManager.getConnection(url, "SA", ""); Statement st = c.createStatement()) {
            st.execute("CREATE TABLE ACCOUNTS (ID VARCHAR(64) PRIMARY KEY, DISPLAYNAME VARCHAR(100), "
                    + "GIVENNAME VARCHAR(100), AGE INTEGER, ACTIVE BOOLEAN, BALANCE DECIMAL(10,2), "
                    + "CREATED TIMESTAMP DEFAULT CURRENT_TIMESTAMP, SERIAL BIGINT GENERATED BY DEFAULT AS IDENTITY, "
                    + "EMAIL VARCHAR(100) DEFAULT '' NOT NULL, CONSTRAINT UQ_EMAIL UNIQUE (DISPLAYNAME))");
            st.execute("CREATE TABLE GROUPS (NAME VARCHAR(64), DESCRIPTION VARCHAR(100))");
        } catch (SQLException e) {
            throw new IllegalStateException(e);
        }
        return url;
    }

    static MapConnectorConfiguration.Builder configuration(String url) {
        return MapConnectorConfiguration.builder()
                .connection(ConnectionSettings.builder().url(url).user("SA").password(SecretValue.of("")).build())
                .property(JdbcConnector.PROP_TABLES, "Account=accounts", "Group=PUBLIC.GROUPS")
                .property(JdbcConnector.PROP_KEY_COLUMNS, "Group=name");
    }
}
